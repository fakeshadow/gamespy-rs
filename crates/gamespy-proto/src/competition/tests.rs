#[test]
fn native_guid_groups_have_network_byte_order_and_reject_alternate_shapes() {
    // Independent native sscanf/store vector: first parsed 0x11223344 is
    // stored as 11 22 33 44, followed by 55 66 and 77 88, not byte-swapped.
    let native = [
        0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee, 0xff,
        0x00,
    ];
    assert_eq!(
        parse_guid("11223344-5566-7788-99AA-BBCCDDEEFF00"),
        Ok(native)
    );
    assert_eq!(format_guid(&native), "11223344-5566-7788-99aa-bbccddeeff00");
    for invalid in [
        "{11223344-5566-7788-99aa-bbccddeeff00}",
        "112233445566778899aabbccddeeff00",
        "11223344-5566-7788-99aa-bbccddeeff0x",
        "11223344_5566-7788-99aa-bbccddeeff00",
    ] {
        assert_eq!(parse_guid(invalid), Err(Error::InvalidGuid));
    }
}

#[test]
fn control_responses_place_fields_inside_native_result_nodes() {
    for operation in [Operation::CreateSession, Operation::CreateMatchlessSession] {
        let xml = build_create_response(operation, 0, "session<&", "connection").unwrap();
        let document = roxmltree::Document::parse(&xml).unwrap();
        let result_name = format!("{}Result", operation.name());
        let result = document
            .descendants()
            .find(|n| n.has_tag_name((NAMESPACE, result_name.as_str())))
            .unwrap();
        assert_eq!(child(result, "result").unwrap().text(), Some("0"));
        assert_eq!(child(result, "csid").unwrap().text(), Some("session<&"));
        assert_eq!(child(result, "ccid").unwrap().text(), Some("connection"));
    }
    assert_eq!(
        build_create_response(Operation::SubmitReport, 0, "", ""),
        Err(Error::UnsupportedOperation)
    );
    let xml = build_intention_response(7, "connection");
    assert!(xml.contains("<SetReportIntentionResult><result>7</result><ccid>connection</ccid>"));
    // 7 is specifically outside the native 0..=6 success interval.
    assert!(build_submit_response(7).contains("<SubmitReportResult><result>7</result>"));
    let xml = build_ban_response(0, 100001, u64::MAX, false);
    let document = roxmltree::Document::parse(&xml).unwrap();
    let config = document
        .descendants()
        .find(|n| n.has_tag_name((NAMESPACE, "UserConfig")))
        .unwrap();
    assert_eq!(
        child(config, "PlatformID").unwrap().text(),
        Some("18446744073709551615")
    );
    assert_eq!(child(config, "IsBanned").unwrap().text(), Some("false"));
}

#[test]
fn proof_is_fixed_sixteen_byte_hex_and_certificate_remains_unverified() {
    let xml = br#"<s:Envelope xmlns:s="http://schemas.xmlsoap.org/soap/envelope/"><s:Body><CreateSession><gameid>2569</gameid><certificate><profileid>100013</profileid></certificate><proof>00112233445566778899AABBCCDDEEFF</proof></CreateSession></s:Body></s:Envelope>"#;
    let request = parse_request(Some("text/xml"), xml).unwrap();
    assert_eq!(
        request.proof,
        Some([
            0, 0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99, 0xaa, 0xbb, 0xcc, 0xdd, 0xee,
            0xff
        ])
    );
    assert_eq!(
        request.certificate_xml,
        Some("<certificate><profileid>100013</profileid></certificate>")
    );
    let xml = std::str::from_utf8(xml)
        .unwrap()
        .replace("00112233445566778899AABBCCDDEEFF", "not-a-proof");
    assert_eq!(
        parse_request(Some("text/xml"), xml.as_bytes()),
        Err(Error::InvalidProof)
    );
}

